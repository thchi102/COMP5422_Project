"""
build_referit3d_manifest.py

Build our project manifest format from ReferIt3D CSV files so the existing
VLM-Grounder wrapper can keep using the same manifest->CSV conversion path.

Default behavior:
- prefer NR3D rows for the requested scenes
- if a requested scene has zero NR3D rows, backfill it from SR3D+
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


def find_project_root(marker: str = "data/schema_v1.json") -> Path:
    for path in [Path.cwd(), *list(Path.cwd().parents)[:6]]:
        if (path / marker).exists():
            return path.resolve()
    raise RuntimeError("Cannot find project root. Run from inside the project directory.")


PROJECT = find_project_root()
DEFAULT_NR3D = PROJECT / "data" / "ReferIt3D" / "nr3d.csv"
DEFAULT_SR3D = PROJECT / "data" / "ReferIt3D" / "sr3d+.csv"


def load_rows(csv_path: Path, scene_filter: set[str] | None = None) -> list[dict]:
    rows: list[dict] = []
    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            scene_id = row.get("scan_id") or row.get("scene_id")
            if scene_filter and scene_id not in scene_filter:
                continue
            rows.append(row)
    return rows


def normalize_query(row: dict, dataset_name: str) -> dict:
    query_id = row.get("assignmentid") or row.get("ann_id") or row.get("utterance_id") or row.get("stimulus_id")
    if query_id is None:
        raise ValueError(f"Could not determine query id for row: {row}")

    utterance = (row.get("utterance") or "").strip()
    if not utterance:
        raise ValueError(f"Empty utterance for query {query_id}")

    scene_id = row.get("scan_id") or row.get("scene_id")
    instance_type = row.get("instance_type") or row.get("target_class") or ""
    target_id = row.get("target_id")
    if target_id is None:
        raise ValueError(f"Missing target_id for query {query_id}")

    distractor_ids_raw = row.get("distractor_ids", "").strip()
    n_distractors = None
    if distractor_ids_raw:
        cleaned = distractor_ids_raw.strip()[1:-1].strip()
        n_distractors = 0 if not cleaned else len([x for x in cleaned.split(",") if x.strip()])

    return {
        "query_id": str(query_id),
        "stimulus_id": row.get("stimulus_id") or f"{scene_id}__{query_id}",
        "scene_id": scene_id,
        "utterance": utterance,
        "target_id": int(target_id),
        "instance_type": instance_type,
        "source_dataset": dataset_name,
        "easy_hard": "hard" if (n_distractors is not None and n_distractors >= 2) else "easy",
        "n_distractors": n_distractors,
        "uses_spatial_lang": row.get("uses_spatial_lang") == "True" if "uses_spatial_lang" in row else None,
        "uses_color_lang": row.get("uses_color_lang") == "True" if "uses_color_lang" in row else None,
    }


def build_manifest(
    out_path: Path,
    scenes: list[str],
    nr3d_path: Path,
    sr3d_path: Path | None,
    max_queries_per_scene: int | None = None,
) -> dict:
    scene_filter = set(scenes)
    manifest_queries: list[dict] = []
    covered_scenes: set[str] = set()

    nr3d_rows = load_rows(nr3d_path, scene_filter)
    for row in nr3d_rows:
        manifest_queries.append(normalize_query(row, "nr3d"))
        covered_scenes.add(row["scan_id"])

    missing_scenes = sorted(scene_filter - covered_scenes)
    if missing_scenes and sr3d_path and sr3d_path.exists():
        sr3d_rows = load_rows(sr3d_path, set(missing_scenes))
        for row in sr3d_rows:
            manifest_queries.append(normalize_query(row, "sr3d+"))

    manifest_queries.sort(key=lambda q: (q["scene_id"], q["query_id"]))

    if max_queries_per_scene is not None:
        counts: dict[str, int] = {}
        trimmed: list[dict] = []
        for query in manifest_queries:
            sid = query["scene_id"]
            count = counts.get(sid, 0)
            if count >= max_queries_per_scene:
                continue
            trimmed.append(query)
            counts[sid] = count + 1
        manifest_queries = trimmed

    present_scenes = sorted({q["scene_id"] for q in manifest_queries})
    manifest = {
        "version": "v1",
        "description": (
            "Autogenerated from ReferIt3D CSV files for VLM-Grounder wrapper use. "
            "NR3D is preferred; SR3D+ backfills scenes missing from NR3D."
        ),
        "scenes": present_scenes,
        "total_queries": len(manifest_queries),
        "queries": manifest_queries,
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Build our manifest format from ReferIt3D CSV files.")
    parser.add_argument("--out", required=True, help="Output manifest JSON path.")
    parser.add_argument("--scenes", nargs="+", required=True, help="Scene ids to include.")
    parser.add_argument("--nr3d", default=str(DEFAULT_NR3D), help="Path to nr3d.csv")
    parser.add_argument("--sr3d", default=str(DEFAULT_SR3D), help="Path to sr3d+.csv")
    parser.add_argument("--max-queries-per-scene", type=int, default=None, help="Optional cap per scene.")
    args = parser.parse_args()

    manifest = build_manifest(
        out_path=Path(args.out).resolve(),
        scenes=args.scenes,
        nr3d_path=Path(args.nr3d).resolve(),
        sr3d_path=Path(args.sr3d).resolve() if args.sr3d else None,
        max_queries_per_scene=args.max_queries_per_scene,
    )
    print(f"[OK] Wrote manifest with {manifest['total_queries']} queries -> {args.out}")
    print(f"[OK] Scenes covered: {manifest['scenes']}")


if __name__ == "__main__":
    main()
